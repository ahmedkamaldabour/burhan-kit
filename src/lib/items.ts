import { acceptedForm } from '../hooks/core/item-model.mjs';
import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';

export interface Item { slug: string; typeScope: string; parent: string; dependsOn: string; state: string; lastActivity: string }

export const GENERATED_MARK = '<!-- generated by burhan status';
export const INDEX_HEADER = [
  `${GENERATED_MARK} — do not edit; run \`burhan status --write\` to refresh -->`,
  '# Work items — index',
  "One line per item, generated from the item files (phases/close-out.md). Detail lives in the item's own files.",
  'States: Draft · Spec ready · Plan ready · In progress · Awaiting QC · QC PASS · Done (no QC) · Paused · Superseded',
  '',
  '| Item | Route | Parent | Depends on | State | Last activity |',
  '|------|-------|--------|------------|-------|---------------|',
];

const STATUS_WORDS = ['In progress', 'Draft', 'Approved', 'Completed', 'Paused', 'Superseded', 'Concluded'];

export function field(text: string, label: string): string | null {
  const esc = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`\\*\\*${esc}:\\*\\*[ \\t]*([^·\\n]*)`).exec(text);
  return m ? m[1].trim() : null;
}

/** Like field(), but the whole rest of the line (for values that themselves contain " · "). */
export function fieldLine(text: string, label: string): string | null {
  const esc = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`\\*\\*${esc}:\\*\\*[ \\t]*([^\\n]*)`).exec(text);
  return m ? m[1].trim() : null;
}

/** null when the value is missing or still a template placeholder (`<…>`). */
export const filled = (v: string | null): string | null => (v === null || v === '' || /<[^>\n]{0,400}>/.test(v) ? null : v);
/** A status field still listing its alternatives (`Draft | Approved`, `Draft → … → Completed`) is unfilled. */
export const choice = (v: string | null): string | null => {
  const f = filled(v);
  return f === null || / \| | → /.test(f) ? null : f.replace(/\*/g, '').trim();
};
const statusWord = (v: string | null): string | null => {
  const f = choice(v);
  return f === null ? null : STATUS_WORDS.find((w) => f.startsWith(w)) ?? null;
};
const verdict = (v: string | null): 'PASS' | 'FAIL' | null => {
  const f = choice(v)?.toUpperCase(); // the same reading as stats (facts.ts qcVerdict)
  return f?.startsWith('PASS') ? 'PASS' : f?.startsWith('FAIL') ? 'FAIL' : null;
};
/** Does the route include the QC gate (WORKFLOW §3)? An unknown route counts as yes — never claim "no QC" by guess. */
export function routeHasQ(typeScope: string): boolean {
  const m = ROUTE.exec(typeScope);
  if (!m) return true;
  const [, type, scope] = m;
  if (type === 'feature') return scope !== 'spike';
  if (type === 'bug' || type === 'change') return scope === 'architectural';
  return false; // investigation, refactor, release
}
export const read = (p: string): string => { try { return readFileSync(p, 'utf8'); } catch { return ''; } };

function deriveState(story: string | null, plan: string | null, findings: string | null, qc: 'PASS' | 'FAIL' | null, accepted: boolean, hasQ: boolean): string {
  switch (plan) {
    case 'Completed':
      if (qc === 'FAIL') return 'In progress';
      if (qc === 'PASS' && accepted) return 'QC PASS';
      return hasQ ? 'Awaiting QC' : 'Done (no QC)';
    case 'In progress': return 'In progress';
    case 'Approved': return 'Plan ready';
    case 'Paused': case 'Superseded': return plan;
  }
  if (story === 'Approved') return 'Spec ready';
  if (findings === 'Concluded') return 'Done (no QC)';
  if (findings === 'In progress') return 'In progress';
  return 'Draft';
}

function lastActivity(projectDir: string, dir: string): string {
  const r = spawnSync('git', ['-C', projectDir, 'log', '-1', '--format=%cs', '--', relative(projectDir, dir) || '.'], { encoding: 'utf8' });
  return r.status === 0 && r.stdout.trim() ? r.stdout.trim() : '—';
}

const NOTHING = /^(—|-|none|n\/a|no|pending|not yet|tbd|todo|waiting|to be filled)(?=$|[\s(:;,.])/i;

// Fields the hooks and stats read have ONE fixed form, read exactly — no word lists, no guessing
// (phases/files.md · "Fields the hooks and stats read"). Anything else means "not given".

/** YYYY-MM-DD that is a real calendar date. */
const isDate = (s: string): boolean => {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) return false;
  const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
  return d.getUTCMonth() === +m[2] - 1 && d.getUTCDate() === +m[3];
};

/** "Reopened after PASS: YYYY-MM-DD — why" (exactly; "—" or anything else = not reopened). */
export const dated = (v: string | null): boolean => {
  const m = /^(\d{4}-\d{2}-\d{2}) — \S/.exec(v?.trim() ?? '');
  return m !== null && isDate(m[1]);
};

/** "Accepted by: <name> · YYYY-MM-DD" (exactly; the name has a letter). Anything else = not accepted. */
export const accepted = (v: string | null): boolean => acceptedForm(v ?? '');

/** "Route: <type> / <scope>" — exactly one listed type and scope, else null. */
export const ROUTE = /^(feature|bug|investigation|change|refactor|release) \/ (spike|bounded|architectural|patch)$/;
export const exactRoute = (v: string | null): string | null => (v !== null && ROUTE.test(v.trim()) ? v.trim() : null);

/** The item's route: **Route:** in the story, plan or findings (legacy **Type / scope:** too), exact form. */
export const itemRoute = (...texts: string[]): string | null => {
  for (const t of texts) for (const label of ['Route', 'Type / scope']) { const r = exactRoute(field(t, label)); if (r) return r; }
  return null;
};

/** A filled value that is not one of the "nothing" markers. */
export const given = (v: string | null): string | null => {
  const f = filled(v);
  const val = f?.replace(/\*/g, '').trim() ?? '';
  // "—", "none", "no", "pending", "not yet" … — alone or followed by an explanation — means nothing.
  return f === null || val === '' || NOTHING.test(val) ? null : val;
};

/** The item's latest QC report: `<slug>-qc-rN.md` with the highest N, else `<slug>-qc.md` (a re-run
 *  supersedes the earlier round). Index and stats both read it. */
export function latestQcFile(dir: string, slug: string): string {
  let names: string[] = [];
  try { names = readdirSync(join(dir, 'reviews')); } catch { /* no reviews yet */ }
  const esc = slug.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const round = (n: string): number => { const m = new RegExp(`^${esc}-qc(?:-r(\\d+))?\\.md$`).exec(n); return m ? Number(m[1] ?? 1) : 0; };
  const best = names.filter((n) => round(n) > 0).sort((a, b) => round(b) - round(a))[0];
  return join(dir, 'reviews', best ?? `${slug}-qc.md`);
}

export function readItem(dir: string, slug: string, projectDir: string): Item {
  const story = read(join(dir, `${slug}-story.md`));
  const plan = read(join(dir, `${slug}-implementation-plan.md`));
  const findings = read(join(dir, `${slug}-findings.md`));
  const qc = read(latestQcFile(dir, slug));
  const typeScope = itemRoute(story, plan, findings) ?? '—';
  return {
    slug,
    typeScope,
    parent: filled(field(story, 'Parent')) ?? '—',
    dependsOn: filled(field(story, 'Depends on')) ?? '—',
    state: deriveState(statusWord(field(story, 'Status')), statusWord(field(plan, 'Overall status')), statusWord(field(findings, 'Status')),
      verdict(field(qc, 'Verdict')), accepted(fieldLine(qc, 'Accepted by')), routeHasQ(typeScope)),
    lastActivity: lastActivity(projectDir, dir),
  };
}

/** Work-item folders: directories only, sorted, dot-dirs skipped. */
export function itemSlugs(docsDir: string): string[] {
  return readdirSync(docsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('.'))
    .map((d) => d.name)
    .sort();
}

export function listItems(docsDir: string, projectDir: string): Item[] {
  return itemSlugs(docsDir).map((slug) => readItem(join(docsDir, slug), slug, projectDir));
}

export function renderIndex(items: Item[]): string {
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  const rows = items.map((i) => `| [${cell(i.slug)}](${encodeURI(i.slug)}/) | ${cell(i.typeScope)} | ${cell(i.parent)} | ${cell(i.dependsOn)} | ${i.state} | ${i.lastActivity} |`);
  return [...INDEX_HEADER, ...rows].join('\n') + '\n';
}
