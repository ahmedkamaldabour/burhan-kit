#!/usr/bin/env bash
. "$(dirname "$0")/../lib.sh"; . "$(dirname "$0")/helpers.sh"
S=prompt-router
r() { core $S "$(ev "$(jq -cn --arg p "$1" '{event:"prompt",prompt:$p}')")" | jq -r '.message // empty'; }
echo "prompt-router.sh"

P="$(proj)"
check "bug (en)" "$(r 'the upload is broken')" has "root cause"
check "bug (ar)" "$(r 'فيه مشكلة في الرفع')" has "root cause"
check "bug (ar, colloquial)" "$(r 'الصفحة مش شغال')" has "root cause"
check "feature (en)" "$(r 'add export to the report')" has "route it"
check "feature (ar)" "$(r 'اضف زرار تصدير')" has "route it"
check "investigation (en) is read-only (R2)" "$(r 'investigate why does the cache miss')" has "read-only"
check "investigation (ar)" "$(r 'عايز افهم الكاش بيشتغل ازاي')" has "read-only"
check "access (en)" "$(r 'change the role permission check')" has "visibility"
check "access (ar)" "$(r 'عدل الصلاحيات')" has "visibility"
check "wrap-up (en)" "$(r 'ok we are done')" has "SHOW the output"
check "wrap-up (ar)" "$(r 'كده خلص')" has "SHOW the output"
check "work-item flow" "$(r 'continue the story foo')" has "burhan:e2e"
check "new command name routes" "$(r 'burhan:qc foo')" has "burhan:qc"
check "branch" "$(r 'open a pull request')" has "human"
check "tests" "$(r 'run the tests')" has "ONE"
check "word boundary: abandoned != done" "$(r 'the abandoned cart page')" lacks "SHOW the output"

out="$(r 'add a fix for the broken role permission, investigate, then we are done')"
check_eq "max 2 suggestions" "$(printf '%s\n' "$out" | grep -c '^•')" "2"
check "highest priority kept (access)" "$out" has "visibility"
check "second priority kept (investigation)" "$out" has "read-only"

check "notification prompts ignored" "$(r '<task-notification> agent done, broken')" lacks "•"
check "system notification ignored" "$(r 'SYSTEM NOTIFICATION: fix broken')" lacks "•"
check "no skill names when skills off" "$(r 'the upload is broken')" lacks "superpowers"
check_eq "no match + skills off -> silent" "$(r 'hello there')" ""

P="$(proj 'WF_SKILLS=superpowers' 'WF_SINGLE_TEST_HINT="tool test {{FILE}}"')"
check "skill names when skills on" "$(r 'the upload is broken')" has "superpowers:systematic-debugging"
check "no match + skills on -> using-superpowers" "$(r 'hello there')" has "superpowers:using-superpowers"
check "tests line shows the single-file hint" "$(r 'run the tests')" has "tool test"
echo "  -- false-positive guards"
check "'scope of this' is not access" "$(r 'what is the scope of this change')" lacks "visibility"
check "'accessibility' is not access" "$(r 'we need accessibility labels')" lacks "visibility"
check "Arabic 'المعدل' is not 'عدل'" "$(r 'ممكن تشرح المعدل ده')" lacks "route it"
check "Arabic 'مخلص' is not 'خلص'" "$(r 'شكرا يا مخلص')" lacks "SHOW the output"
check "local-command-caveat ignored" "$(r '<local-command-caveat>fix broken</local-command-caveat>')" lacks "•"
echo "  -- more Arabic"
check "work-item (ar)" "$(r 'كمل الستوري')" has "burhan:e2e"
check "branch (ar)" "$(r 'اعمل دمج للفرع')" has "human"
check "tests (ar)" "$(r 'شغل التست')" has "ONE"
check "investigation phrase (ar)" "$(r 'ليه بيحصل كده في الكاش')" has "read-only"
P="$(proj 'WF_SINGLE_TEST_HINT="tool a&b {{FILE}}"')"
check "& in hint survives" "$(r 'run the tests')" has "tool a&b <file>"
echo "  -- patch lane"
P="$(proj)"
check "typo -> patch lane with its limits" "$(r 'fix the typo in the README')" has "patch"
check "...and the limits are stated" "$(r 'fix the typo in the README')" has "any doubt"
check "one line (ar) -> patch lane" "$(r 'صلح غلطة إملائية في الرسالة')" has "patch"
check "a typo in an access rule -> the access line comes first" "$(r 'fix the typo in the role permission check')" has "visibility"
echo "  -- mode switches"
P="$(proj)"
check "go on your own -> auto, brakes still stop" "$(r 'go end to end, do not wait for me')" has "**Mode:** auto"
check "Arabic switch to auto" "$(r 'كمل لوحدك للاخر')" has "**Mode:** auto"
check "wait for my approval -> step" "$(r 'wait for my approval after each step')" has "**Mode:** step"
check "Arabic switch to step" "$(r 'استنى موافقتي')" has "**Mode:** step"
check "Arabic switch to step, the other spelling" "$(r 'استني موافقتي')" has "**Mode:** step"
check "the switch line says the bold field the hooks read" "$(r 'go end to end, do not wait for me')" has '**Mode:** auto'
check "'end to end tests' is not a mode switch" "$(r 'add end to end tests for the role permissions page')" lacks "Mode switch"
check "...so the bug line survives the cap" "$(r 'the end to end test fails on the tenant filter')" has "Bug"
check "'explain step by step' is not a mode switch" "$(r 'explain step by step how the access rules work')" lacks "Mode switch"
check "renaming a column in a migration is no patch" "$(r 'rename the orders.total column in the migration')" lacks "patch lane"
for q in 'plan only for the export feature' 'just the plan please' 'اعمل الخطة بس' 'خطة بس من غير كود'; do
  check "'$q' -> the plan-only stopping point (a suggestion, not a mode)" "$(r "$q")" has "Plan only"
  check "...which is no mode switch" "$(r "$q")" lacks "Mode switch"
done
check "plan only + a step phrase -> step wins" "$(r 'plan only, and wait for my approval')" has "**Mode:** step"
check "...and no plan-only line" "$(r 'plan only, and wait for my approval')" lacks "Plan only"
check "'the plan only covers phase 1' is no request for a plan" "$(r 'the plan only covers phase 1, fix the bug')" lacks "Plan only"
for q in 'only the plan file changed' 'only the plan covers phase 1' 'الخطة بس بتغطي المرحلة الأولى'; do
  check "'$q' is no plan-only request" "$(r "$q")" lacks "Plan only"
done
check "plan only + go end to end -> both the auto switch and the stopping point" "$(r 'plan only, then go end to end')" has "Plan only"
check "'run end to end tests' is a request, not a switch" "$(r 'run end to end tests on staging')" lacks "Mode switch"
check "a negated auto phrase plus a step phrase -> step (the safer gate)" "$(r "don't go end to end, wait for my approval")" has "**Mode:** step"
check "...in Arabic too" "$(r 'متعملش ده لوحدك، استنى موافقتي')" has "**Mode:** step"
check "'on your own branch' is not a switch" "$(r 'push it on your own branch')" lacks "Mode switch"
check "a negated step phrase is no step switch" "$(r "don't wait for my approval, go end to end")" has "**Mode:** auto"
check "hyphenated end-to-end tests are a request" "$(r 'the end-to-end tests fail on staging')" lacks "Mode switch"
check "hyphenated go end-to-end -> auto" "$(r 'please go end-to-end')" has "**Mode:** auto"
check "a negated hyphenated end-to-end is no switch" "$(r "don't go end-to-end yet")" lacks "**Mode:** auto"
check "a bare لوحدك in another sense is no switch" "$(r 'الملف ده لوحدك فيه مشكلة')" lacks "Mode switch"
echo "  -- without a UTF-8 locale (a hook may run under LC_ALL=C, or with no locale set at all)"
for loc in LC_ALL=C LANG=; do
  rc() { ( unset LANG LC_ALL LC_CTYPE; export "$loc"; r "$1" ); }
  check "Arabic step switch, $loc" "$(rc 'استنى موافقتي')" has "**Mode:** step"
  check "Arabic plan-only stopping point, $loc" "$(rc 'اعمل الخطة بس')" has "Plan only"
  check "Arabic auto switch, $loc" "$(rc 'كمّل لوحدك')" has "**Mode:** auto"
done
t_summary
