#!/usr/bin/env bash
. "$(dirname "$0")/../lib.sh"; . "$(dirname "$0")/helpers.sh"
S=session-gates
echo "session-gates.sh"

P="$(proj 'WF_STATE_FILE="state/NOW.md"')"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "emits the gates" "$out" has "WORKFLOW GATES"
check "{{STATE_FILE}} replaced" "$out" has "state/NOW.md"
check "no raw placeholders left" "$out" lacks "{{"
check "route-first reminder (R1)" "$out" has "type + scope"
check "discover-before-asking (R3)" "$out" has "DISCOVER BEFORE ASKING"
check "...including what the repository cannot give" "$out" has "what the repository cannot give"
check "no check line when WF_CHECK_CMD empty" "$out" lacks "FAST CHECK"
check "no forbidden line when reason empty" "$out" lacks "NEVER RUN"
check "no skills line when WF_SKILLS=none" "$out" lacks "superpowers"
check "no state block when state file missing" "$out" lacks "CURRENT STATE"

P="$(proj 'WF_CHECK_CMD="make check"' 'WF_FORBIDDEN_REASON="it melts the laptop"' 'WF_SKILLS=superpowers')"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "check line shows the command" "$out" has "make check"
check "legacy reason is ignored" "$out" lacks "it melts the laptop"
check "legacy reason emits no NEVER RUN gate" "$out" lacks "NEVER RUN"
check "legacy reason emits no FORBIDDEN text" "$out" lacks "FORBIDDEN"
check "skills line when enabled" "$out" has "superpowers:using-superpowers"

# R14 — the state file's Now section is surfaced
mkdir -p "$P/.burhan/local"
{ echo "# PROGRESS"; echo "## Now"; echo "### foo"; echo "- **Primary objective:** ship AC-03";
  echo "## Waiting on you"; echo "- secret-ish detail that must not be shown"; } > "$P/.burhan/local/PROGRESS.md"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "state block present (R14)" "$out" has "CURRENT STATE"
check "Now section content shown" "$out" has "Primary objective:** ship AC-03"
check "only the Now section is shown" "$out" lacks "secret-ish detail"

# Session links: with more than one in-flight item an unlinked session must not silently inherit the
# first block. Black-box coverage: tests/impl.sh runs it against the Node hooks (or WF_IMPL_CORE).
P="$(proj 'WF_MODE_DEFAULT=auto')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### alpha' '- **Mode:** step' '### beta' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
out="$(core $S "$(ev '{"event":"session_start","session":"S-unlinked"}')" | jq -r .message)"
check "several items with no link ask which item" "$out" has "this session isn't linked to one yet — say which, or run /burhan:e2e <slug>."
check "several items with no link do not apply alpha's mode" "$out" has "MODE: auto"
check_eq "shared exact unlinked item list uses Node-style separators" \
  "$(printf '%s\n' "$out" | awk '/⚑ ITEMS IN FLIGHT:/{print; exit}')" \
  "⚑ ITEMS IN FLIGHT: alpha, beta — this session isn't linked to one yet — say which, or run /burhan:e2e <slug>."

# External links are the shared contract for Bash and the Node port.  Cover linked, stale, and
# single-item fallback through the same black-box suite.
EVD="$(t_tmp)/session-links"; export WF_EVIDENCE_DIR="$EVD"
KEY="$(cd "$P" && pwd -P | tr -d '\n' | t_sha | cut -c1-16)"
mkdir -p "$EVD/$KEY/S-linked"; printf '%s\n' beta > "$EVD/$KEY/S-linked/item"
out="$(core $S "$(ev '{"event":"session_start","session":"S-linked"}')" | jq -r .message)"
check_eq "shared linked session shows selected block and exactly joined others" \
  "$(printf '%s\n' "$out" | awk '/⚑ CURRENT STATE .*linked: beta\):/{on=1} on{print} /⚑ OTHER ITEMS:/{exit}')" \
  $'⚑ CURRENT STATE (.burhan/local/PROGRESS.md · Now · linked: beta):\n### beta\n- **Mode:** auto\n⚑ OTHER ITEMS: alpha'
mkdir -p "$EVD/$KEY/S-stale"; printf '%s\n' closed > "$EVD/$KEY/S-stale/item"
out="$(core $S "$(ev '{"event":"session_start","session":"S-stale"}')" | jq -r .message)"
check_eq "shared stale link falls back to the unlinked multi-item message" \
  "$(printf '%s\n' "$out" | awk '/⚑ ITEMS IN FLIGHT:/{print; exit}')" \
  "⚑ ITEMS IN FLIGHT: alpha, beta — this session isn't linked to one yet — say which, or run /burhan:e2e <slug>."
printf '%s\n' '## Now' '### alpha' '- **Mode:** step' > "$P/.burhan/local/PROGRESS.md"
out="$(core $S "$(ev '{"event":"session_start","session":"S-stale"}')" | jq -r .message)"
check_eq "shared stale link uses the sole live item" \
  "$(printf '%s\n' "$out" | awk '/⚑ CURRENT STATE/{print; exit}')" \
  "⚑ CURRENT STATE (.burhan/local/PROGRESS.md · Now):"
unset WF_EVIDENCE_DIR

{ echo "## Now"; seq 1 50 | sed 's/^/- line /'; echo "## Standing facts"; } > "$P/.burhan/local/PROGRESS.md"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "long Now section truncated" "$out" has "truncated"
check "lines beyond 30 not shown" "$out" lacks "- line 40"
# & in a value must not be expanded by bash 5.2 patsub_replacement (review: Critical)
P="$(proj 'WF_CHECK_CMD="make lint && make test"')"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "& in a config value survives substitution" "$out" has "make lint && make test"
check "no placeholder leaked by &" "$out" lacks "{{"
P="$(proj 'WF_SKILLS=other-plugin')"
check "unknown WF_SKILLS value -> no superpowers names" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" lacks "superpowers"
P="$(proj)"; mkdir -p "$P/.burhan/local"
{ echo "## Now"; printf -- '- %*s\n' 300000 x | tr ' ' 'y'; } > "$P/.burhan/local/PROGRESS.md"
check "a huge line in Now does not suppress the gates" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "WORKFLOW GATES"
echo "  -- first-use trigger (WF_STACK_SETUP)"
FU="⚑ FIRST USE: burhan's project checks are not set up yet. Before other work, run \`npx burhan-kit setup --stack\` and follow it."
P="$(proj 'WF_STACK_SETUP=pending')"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "FIRST USE line when WF_STACK_SETUP=pending" "$out" has "$FU"
check "...and the gates are still there" "$out" has "WORKFLOW GATES"
for v in 'WF_STACK_SETUP=done' 'WF_STACK_SETUP=' 'WF_STACK_SETUP=Pending' 'WF_STACK_SETUP=other'; do
  P="$(proj "$v")"
  check "no FIRST USE line for $v" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" lacks "FIRST USE"
done
P="$(proj)"
check "no FIRST USE line when the key is absent" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" lacks "FIRST USE"
echo "  -- autonomy modes"
P="$(proj)"
out="$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)"
check "default mode is step" "$out" has "MODE: step"
check "modes are worded as flow gates, not permissions" "$out" has "not the agent's permission mode"
P="$(proj 'WF_MODE_DEFAULT=auto')"
check "WF_MODE_DEFAULT applies" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "MODE: auto"
mkdir -p "$P/.burhan/local"; printf '%s\n' '## Now' '### foo' '- **Mode:** plan-only' > "$P/.burhan/local/PROGRESS.md"
check "an old Mode: plan-only is no mode any more -> step, the safer gate (plan-only removed before 0.1.0)" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "MODE: step"
check "...and one line says plan-only is no longer a mode" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "plan-only is no longer a mode"
printf '%s\n' '## Now' '### foo' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
check "the item's Mode in the state file wins" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "MODE: auto"
check "...and no plan-only notice without plan-only" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" lacks "plan-only"
P="$(proj 'WF_MODE_DEFAULT=yolo')"
check "an unknown mode falls back to step" "$(core $S "$(ev '{"event":"session_start"}')" | jq -r .message)" has "MODE: step"
sg() { core $S "$(ev '{"event":"session_start"}')" | jq -r .message; }
P="$(proj 'WF_MODE_DEFAULT=auto')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### foo' '- **Mode:** Step' > "$P/.burhan/local/PROGRESS.md"
check "**Mode:** with a value outside step|auto -> step, never the default (fixed format)" "$(sg)" has "MODE: step"
for line in '- Type / scope: bug / bounded · Mode: step' '- **Mode**: step'; do
  printf '%s\n' '## Now' '### foo' "$line" > "$P/.burhan/local/PROGRESS.md"
  check "not the **Mode:** field ($line) -> no item mode; the default applies (fixed format, no guessing)" "$(sg)" has "MODE: auto"
done
printf '%s\n' '## Now' '### foo' '- **Mode:** whenever' > "$P/.burhan/local/PROGRESS.md"
check "a Mode label that cannot be read -> step, never the default" "$(sg)" has "MODE: step"
printf '%s\n' '## Now' '### foo' '- **Mode:** step (was Mode: auto)' > "$P/.burhan/local/PROGRESS.md"
check "the first Mode value on the line counts, never a later one" "$(sg)" has "MODE: step"
P="$(proj 'WF_MODE_BUG_BOUNDED=auto')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### fix-x' '- **Type / scope:** bug / bounded' > "$P/.burhan/local/PROGRESS.md"
check "WF_MODE_<TYPE>_<SCOPE> applies to the item's route" "$(sg)" has "MODE: auto"
printf '%s\n' '## Now' '### feat-x' '- **Type / scope:** feature / architectural' > "$P/.burhan/local/PROGRESS.md"
check "...and not to another route" "$(sg)" has "MODE: step"
printf '%s\n' '## Now' '### fix-x' '- **Type / scope:** bug / bounded · **Read-only:** no · **Mode:** <step | auto>' > "$P/.burhan/local/PROGRESS.md"
check "an unfilled template Mode falls through to the route's key" "$(sg)" has "MODE: auto"
printf '%s\n' '## Now' '### fix-x' '- **Type / scope:** bug / architectural' '### other' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
check "another item's Mode never becomes the session's mode" "$(sg)" has "MODE: step"
printf '%s\n' '## Now' '### fix-x' '- **Type / scope:** bug / architectural' '- Note: dark mode: auto in the UI' > "$P/.burhan/local/PROGRESS.md"
check "a prose 'dark mode: auto' is no Mode field" "$(sg)" has "MODE: step"
check "the gates say the pause between sub-units is step mode's" "$(sg)" has "pause between sub-units in step mode"
P="$(proj)"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### fix-x' '- **Route:** bug / architectural' '### <slug>' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
check "a template block after the item is not part of it" "$(sg)" has "MODE: step"
printf '%s\n' '## Now' '### fix-x' '- **Route:** bug / architectural' '#### notes' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
check "a #### sub-heading inside the item does not end it" "$(sg)" has "MODE: auto"
P="$(proj 'WF_MODE_DEFAULT=auto')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### foo' '- **Mode:** Auto' > "$P/.burhan/local/PROGRESS.md"
check "a malformed Mode is step even when the default is auto (never loosens the gate)" "$(sg)" has "MODE: step"
P="$(proj 'WF_MODE_DEFAULT=plan-only')"; mkdir -p "$P/.burhan/local"; printf '%s\n' '## Now' '### b' '- **Route:** bug / bounded' > "$P/.burhan/local/PROGRESS.md"
check "WF_MODE_DEFAULT=plan-only (old config) -> step" "$(sg)" has "MODE: step"
check "...with the plan-only notice" "$(sg)" has "plan-only is no longer a mode"
P="$(proj 'WF_MODE_DEFAULT=auto' 'WF_MODE_BUG_BOUNDED=whenever')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### b' '- **Route:** bug / bounded' > "$P/.burhan/local/PROGRESS.md"
check "an invalid route mode key is step, never the looser default" "$(sg)" has "MODE: step"
P="$(proj 'WF_MODE_DEFAULT=auto' 'WF_MODE_RELEASE_ARCHITECTURAL=plan-only')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### r' '- **Route:** release / architectural' > "$P/.burhan/local/PROGRESS.md"
check "an old per-route plan-only key is step, not the default auto" "$(sg)" has "MODE: step"
check "...and the notice names the key" "$(sg)" has "WF_MODE_RELEASE_ARCHITECTURAL"
P="$(proj 'WF_MODE_DEFAULT=plan-only')"; mkdir -p "$P/.burhan/local"
printf '%s\n' '## Now' '### a' '- **Mode:** auto' > "$P/.burhan/local/PROGRESS.md"
check "an explicit item Mode wins over an old plan-only default" "$(sg)" has "MODE: auto"
check "...and the notice states the real mode, never a false 'step'" "$(sg)" has "this session runs as auto"
printf '%s\n' '## Now' '### a' '- **Mode:** Plan Only' > "$P/.burhan/local/PROGRESS.md"
check "a plan-only written another way is step, with the notice" "$(sg)" has "plan-only is no longer a mode"
P="$(proj 'WF_FORBIDDEN_REGEX="rm -rf"')"
check "legacy regex emits no NEVER RUN gate" "$(sg)" lacks "NEVER RUN"
check "legacy regex emits no FORBIDDEN text" "$(sg)" lacks "FORBIDDEN"
mkdir -p "$P/.burhan/local"
printf '%s\n' 'WF_FORBIDDEN_REASON="legacy local reason"' 'WF_SINGLE_TEST_HINT="legacy local runner {{FILE}}"' > "$P/.burhan/local/workflow.config"
out="$(sg)"
check "legacy local reason is ignored" "$out" lacks "legacy local reason"
check "legacy local hint is ignored" "$out" lacks "legacy local runner"
t_summary
